"""
Generates synthetic evaluator datasets for training and validation.

NOTE ON DATASET INTENT:
The datasets generated by this script using construction-based labeling
or mock-judging are DEVELOPMENT / BOOTSTRAP datasets. They are designed for:
1. Validating schemas and data loaders.
2. Training loss-function pipelines (BCE / focal loss) end-to-end.
3. Regression and contract testing.

They should NOT be treated as certified ground-truth evaluator labels.
For production-grade evaluation, use independent LLM judging with verified
provider credentials or human-annotated test sets.

Usage:
    python scripts/generate_evaluator_datasets.py --corpus-path data/processed/corpus.jsonl --output-dir data/synthetic
"""

import argparse
import sys
from pathlib import Path

# Ensure project root is in sys.path for direct script invocation
PROJECT_ROOT = Path(__file__).resolve().parent.parent
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from src.core.dataset import load_corpus_from_jsonl
from src.retrieval.sparse import BM25Retriever
from src.synthetic_data.generator import MockDeterministicGenerator
from src.synthetic_data.judge import MockEvaluatorJudge
from src.synthetic_data.pipeline import SyntheticDataPipeline


def parse_args():
    parser = argparse.ArgumentParser(
        description="Generate development train/val datasets for the CRAG evaluator."
    )
    parser.add_argument(
        "--corpus-path",
        type=str,
        default="data/processed/corpus.jsonl",
        help="Path to source corpus JSONL.",
    )
    parser.add_argument(
        "--output-dir",
        type=str,
        default="data/synthetic",
        help="Directory to save evaluator_train.jsonl and evaluator_val.jsonl.",
    )
    parser.add_argument(
        "--train-count",
        type=int,
        default=40,
        help="Number of documents allocated to the training split (remaining to val).",
    )
    parser.add_argument(
        "--judge",
        choices=["none", "mock"],
        default="none",
        help="Labeling judge: 'none' (construction-strategy based) or 'mock' (rule-based MockEvaluatorJudge).",
    )
    parser.add_argument(
        "--seed",
        type=int,
        default=42,
        help="Random seed for deterministic generation.",
    )
    return parser.parse_args()


def main():
    args = parse_args()
    corpus_path = Path(args.corpus_path)
    output_dir = Path(args.output_dir)

    if not corpus_path.exists():
        print(f"Error: Corpus file not found at {corpus_path}", file=sys.stderr)
        sys.exit(1)

    print(f"Loading corpus from: {corpus_path}")
    corpus = load_corpus_from_jsonl(corpus_path)
    total_docs = len(corpus)
    print(f"Loaded {total_docs} documents.")

    if total_docs < 2:
        print("Error: Corpus must contain at least 2 documents to split into train and val.", file=sys.stderr)
        sys.exit(1)

    train_count = min(args.train_count, total_docs - 1)
    train_corpus = corpus[:train_count]
    val_corpus = corpus[train_count:]

    print(f"Split: {len(train_corpus)} train documents, {len(val_corpus)} validation documents.")
    print("=" * 70)
    print("NOTICE: Generating DEVELOPMENT bootstrap datasets.")
    print("These labels are heuristic/mock assignments for offline pipeline validation.")
    print("=" * 70)

    output_dir.mkdir(parents=True, exist_ok=True)
    train_path = output_dir / "evaluator_train.jsonl"
    val_path = output_dir / "evaluator_val.jsonl"

    # Setup judge if specified
    judge_instance = MockEvaluatorJudge() if args.judge == "mock" else None

    # 1. Train split generation
    print("\n[1/2] Indexing train corpus with BM25...")
    bm25_train = BM25Retriever()
    bm25_train.index(train_corpus)

    pipeline_train = SyntheticDataPipeline(
        corpus=train_corpus,
        generator=MockDeterministicGenerator(),
        retriever=bm25_train,
        judge=judge_instance,
        seed=args.seed,
    )
    print(f"Generating train dataset -> {train_path}...")
    train_examples, train_report = pipeline_train.generate_and_save(
        output_path=train_path,
        num_hard_negatives_per_query=1,
        num_random_negatives_per_query=1,
    )
    print(f"Train set: {len(train_examples)} examples. Valid: {train_report.is_valid}")
    if not train_report.is_valid:
        print(f"Train validation errors: {train_report.errors}", file=sys.stderr)

    # 2. Validation split generation
    print("\n[2/2] Indexing validation corpus with BM25...")
    bm25_val = BM25Retriever()
    bm25_val.index(val_corpus)

    pipeline_val = SyntheticDataPipeline(
        corpus=val_corpus,
        generator=MockDeterministicGenerator(),
        retriever=bm25_val,
        judge=judge_instance,
        seed=args.seed + 100,
    )
    print(f"Generating validation dataset -> {val_path}...")
    val_examples, val_report = pipeline_val.generate_and_save(
        output_path=val_path,
        num_hard_negatives_per_query=1,
        num_random_negatives_per_query=1,
    )
    print(f"Val set: {len(val_examples)} examples. Valid: {val_report.is_valid}")
    if not val_report.is_valid:
        print(f"Val validation errors: {val_report.errors}", file=sys.stderr)

    print("\n" + "=" * 70)
    print("Summary of Generated Datasets:")
    print(f"  Train: {train_path} ({len(train_examples)} records)")
    print(f"  Val:   {val_path} ({len(val_examples)} records)")
    print("  Schema: EvaluatorExample (query, document_id, passage_text, labels, metadata)")
    print("  Target consumers: Member 2 (DeBERTa-v3 training) & Member 3 (evaluator baseline)")
    print("=" * 70)


if __name__ == "__main__":
    main()
